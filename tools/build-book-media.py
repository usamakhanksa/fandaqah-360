"""Build the campaign book's media: web copies of banners and creatives, plus book/media/manifest.js.

Usage:  python -I tools/build-book-media.py
Sources (internal, never published):  campaigns/<X>/banners/*.png  ·  campaigns/<X>/creatives/{feed,story,carousel}/*.jpg
Output  (published with the book):    book/media/<X>/{banners,feed,story,carousel}/*.webp  ·  book/media/manifest.js
Reels are rendered separately by tools/render-reels.mjs into book/media/<X>/reels/ and picked up here when present.
"""
import json, re, sys, pathlib, subprocess
from PIL import Image

sys.stdout.reconfigure(encoding='utf-8')
ROOT = pathlib.Path(__file__).resolve().parent.parent
FOLDERS = {'A': 'A-existing-customers', 'B': 'B-new-hotels', 'C': 'C-opera-pms', 'D': 'D-hotel-groups'}
WIDTH = {'banners': 1080, 'feed': 1080, 'story': 720, 'carousel': 1080}


def webp(src, dst, width, quality=80):
    dst.parent.mkdir(parents=True, exist_ok=True)
    im = Image.open(src).convert('RGB')
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    im.save(dst, 'WEBP', quality=quality, method=6)
    return im.width, im.height


def rel(p):
    return p.relative_to(ROOT / 'book').as_posix()


manifest, total = {}, 0
for code, folder in FOLDERS.items():
    camp, out = ROOT / 'campaigns' / folder, ROOT / 'book' / 'media' / folder
    entry = {'banners': [], 'feed': [], 'story': [], 'carousel': [], 'reels': {}}
    # designed banners, titled from campaigns/<X>/banners/README.md
    titles = {}
    readme = camp / 'banners' / 'README.md'
    if readme.exists():
        for name, title in re.findall(r'^\| `([^`]+)` \| (.+?) \| `', readme.read_text(encoding='utf-8'), re.M):
            titles[name] = re.sub(r'\s*\((dark|variant)\)$', '', title)
    for src in sorted((camp / 'banners').glob('*.png')):
        dst = out / 'banners' / (src.stem + '.webp')
        w, h = webp(src, dst, WIDTH['banners'], 82)
        lang = 'ar' if src.stem.endswith('-ar') else 'en'
        entry['banners'].append({'src': rel(dst), 'w': w, 'h': h, 'lang': lang, 'title': titles.get(src.name, src.stem)})
    # studio creatives
    for kind in ('feed', 'story', 'carousel'):
        for src in sorted((camp / 'creatives' / kind).glob('*.jpg')):
            dst = out / kind / (src.stem + '.webp')
            w, h = webp(src, dst, WIDTH[kind])
            entry[kind].append({'src': rel(dst), 'w': w, 'h': h, 'lang': src.stem.rsplit('-', 1)[-1], 'name': src.stem})
    # reels (rendered by tools/render-reels.mjs); only <X>-reel-<lang>.mp4, so other videos never replace a reel
    for mp4 in sorted((out / 'reels').glob('*-reel-*.mp4')):
        lang = mp4.stem.rsplit('-', 1)[-1]
        entry['reels'][lang] = {'mp4': rel(mp4), 'poster': rel(mp4.with_suffix('.jpg')), 'mb': round(mp4.stat().st_size / 1048576, 1)}
    # Snapchat ads (tools/render-snap.mjs): <X>-snap-<lang>.mp4 (motion) and <X>-snap2-<lang>.mp4 (receptionist film),
    # offered in the book's downloads beside the reels; keyed by ad and language, e.g. snap2-ar
    for mp4 in sorted((out / 'reels').glob('*-snap*-*.mp4'), key=lambda f: f.stem, reverse=True):
        lang = mp4.stem.rsplit('-', 1)[-1]
        probe = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(mp4)], capture_output=True, text=True)
        sec = round(float(probe.stdout.strip() or 0))
        kind = mp4.stem.split('-')[1]
        entry.setdefault('snap', {})[f'{kind}-{lang}'] = {'kind': kind, 'lang': lang, 'mp4': rel(mp4), 'poster': rel(mp4.with_suffix('.jpg')), 'mb': round(mp4.stat().st_size / 1048576, 1), 'sec': sec}
    manifest[code] = entry
    n = sum(len(entry[k]) for k in ('banners', 'feed', 'story', 'carousel'))
    total += n
    print(f'{code}: {len(entry["banners"])} banners, {len(entry["feed"])} feed, {len(entry["story"])} story, {len(entry["carousel"])} carousel, reels: {sorted(entry["reels"])}')

(ROOT / 'book' / 'media' / 'manifest.js').write_text(
    '/* Generated by tools/build-book-media.py: do not edit by hand. */\nwindow.BOOK_MEDIA = ' + json.dumps(manifest, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')
size = sum(p.stat().st_size for p in (ROOT / 'book' / 'media').rglob('*') if p.is_file() and p.suffix == '.webp')
print(f'{total} images, {size / 1048576:.1f} MB of WebP, manifest written')
