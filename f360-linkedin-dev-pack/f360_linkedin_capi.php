<?php
/**
 * Fandaqah 360 · LinkedIn Conversions API (CAPI) sender
 * ------------------------------------------------------------------
 * Account 507948919 · conversion rules created 27 Oct 2026 (data source: Direct API)
 *
 *   32466657  F360_Lead_Submit      | Web form success | CAPI (server)   -> twin of Insight Tag rule 32466609
 *   32466633  F360_Qualified_Lead   | CRM stage = Qualified
 *   32466641  F360_Sales_Opportunity| CRM stage = Opportunity
 *   32466649  F360_Customer         | CRM stage = Closed Won
 *
 * Requirements
 *   - LinkedIn developer app with Marketing API access + scope rw_conversions,
 *     token generated by a user with Campaign Manager access to account 507948919.
 *   - Store the token in env LINKEDIN_CAPI_TOKEN (never in client JS).
 *   - LINKEDIN_API_VERSION must be a currently-supported YYYYMM version
 *     (LinkedIn retires versions ~12 months after release — check before go-live).
 *
 * Matching keys LinkedIn accepts (at least one required):
 *   SHA256_EMAIL, LINKEDIN_FIRST_PARTY_ADS_TRACKING_UUID (li_fat_id),
 *   or userInfo {firstName + lastName + companyName/title}.
 *   Phone number is NOT a LinkedIn match key.
 */

const F360_CAPI = [
    'lead_submit'  => 32466657,
    'qualified'    => 32466633,
    'opportunity'  => 32466641,
    'customer'     => 32466649,
];

function f360_capi_send(string $stage, array $lead): array
{
    if (!isset(F360_CAPI[$stage])) {
        return ['ok' => false, 'error' => 'unknown stage ' . $stage];
    }

    $userIds = [];
    $email = strtolower(trim((string)($lead['email'] ?? '')));
    if ($email !== '' && filter_var($email, FILTER_VALIDATE_EMAIL)) {
        $userIds[] = ['idType' => 'SHA256_EMAIL', 'idValue' => hash('sha256', $email)];
    }
    $fat = trim((string)($lead['li_fat_id'] ?? ''));
    if ($fat !== '') {
        $userIds[] = ['idType' => 'LINKEDIN_FIRST_PARTY_ADS_TRACKING_UUID', 'idValue' => $fat];
    }

    $userInfo = array_filter([
        'firstName'   => $lead['first_name'] ?? null,
        'lastName'    => $lead['last_name'] ?? null,
        'companyName' => $lead['company'] ?? null,
        'title'       => $lead['title'] ?? null,
        'countryCode' => 'SA',
    ]);

    // Without email or li_fat_id the event can still be sent with name+company,
    // but match rates drop sharply. Log it so the gap is visible.
    if (!$userIds && !(isset($userInfo['firstName'], $userInfo['lastName']) && (isset($userInfo['companyName']) || isset($userInfo['title'])))) {
        return ['ok' => false, 'error' => 'no matchable identifier (phone-only record)'];
    }

    // LinkedIn accepts conversions up to 90 days old.
    $happenedMs = (int)($lead['occurred_at_ms'] ?? round(microtime(true) * 1000));
    if ($happenedMs < (time() - 89 * 86400) * 1000) {
        return ['ok' => false, 'error' => 'older than 90 days - LinkedIn will reject'];
    }

    $event = [
        'conversion'           => 'urn:lla:llaPartnerConversion:' . F360_CAPI[$stage],
        'conversionHappenedAt' => $happenedMs,
        // Same id as the browser event for lead_submit; stage-suffixed for later stages.
        // Fallback (e.g. Lead Gen Form leads with no submission_id): stable hash of identity + stage.
        'eventId'              => (($lead['submission_id'] ?? '') !== ''
                                    ? $lead['submission_id']
                                    : substr(hash('sha256', $email . '|' . $fat . '|' . ($lead['li_lead_urn'] ?? '')), 0, 32))
                                  . ($stage === 'lead_submit' ? '' : ':' . $stage),
        'user'                 => array_filter(['userIds' => $userIds, 'userInfo' => $userInfo ?: null]),
    ];
    if (isset($lead['value_sar'])) {
        // Campaign Manager account currency is USD.
        $event['conversionValue'] = ['currencyCode' => 'USD', 'amount' => number_format($lead['value_sar'] / 3.75, 2, '.', '')];
    }
    // Lead Gen Form leads: pass the LinkedIn lead response URN when your CRM stored it
    // (enables "Qualified leads" optimisation). Field name per LinkedIn CAPI docs - verify on your API version.
    if (!empty($lead['li_lead_urn'])) {
        $event['lead'] = $lead['li_lead_urn']; // e.g. urn:li:leadGenFormResponse:xxxxxxxx
    }

    $ch = curl_init('https://api.linkedin.com/rest/conversionEvents');
    curl_setopt_array($ch, [
        CURLOPT_POST           => true,
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_TIMEOUT        => 10,
        CURLOPT_HTTPHEADER     => [
            'Authorization: Bearer ' . getenv('LINKEDIN_CAPI_TOKEN'),
            'Content-Type: application/json',
            'LinkedIn-Version: ' . (getenv('LINKEDIN_API_VERSION') ?: '202610'),
            'X-Restli-Protocol-Version: 2.0.0',
        ],
        CURLOPT_POSTFIELDS     => json_encode($event, JSON_UNESCAPED_UNICODE),
    ]);
    $body = curl_exec($ch);
    $code = curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);

    error_log(sprintf('[F360 CAPI] stage=%s id=%s http=%d', $stage, $event['eventId'], $code));
    return ['ok' => $code === 201, 'http' => $code, 'body' => $body];
}
